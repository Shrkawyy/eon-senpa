const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const code=fs.readFileSync(__dirname+'/src/eonSenpaBots.js','utf8');
const events={}, docEvents={};
const children=[];
const body={append:el=>children.push(el)};
const root={URL, Date, Math, Number, JSON, console, performance, document:{hidden:false,body, addEventListener:(k,fn)=>(docEvents[k] ||= []).push(fn),createElement:tag=>({tagName:tag,style:{},textContent:'',setAttribute(){}})},addEventListener:(k,fn)=>(events[k] ||= []).push(fn),setTimeout,clearTimeout};
root.window=root;
vm.runInNewContext(code,root);
const m=Object.create(root.EonSenpaBots.Manager.prototype);
const canvas={getBoundingClientRect:()=>({left:10,top:20,width:1000,height:600,right:1010,bottom:620})};
const main={isConnected:true,clientReady:true,authCompleted:true,probeUrl:'wss://eu1.senpa.io:7101',tabs:[],player:{cells:[]}};
const stage={canvas,camera:{x:2000,y:3000,zoom:.5},border:{left:0,top:0,right:22000,bottom:22000}};
m.app={stage,gameConnection:{primary:main,current:main},settingsMenu:{isVisible:false},lobby:{isVisible:false},replayManager:{isReplay:false}};
m.followMode='mouse'; m.controls={follow:true,respawn:false,split:false,feed:false}; m.rightHeld=false; m.rightScreen=null; m.rightMarker=null; m.rightReleaseAction='disconnect';
m.botLogs=[]; m.panel={querySelector:()=>({textContent:''})}; m.typing=()=>false; m.bots=[];
let disconnects=0; m.disconnectAll=()=>{disconnects++};
m.initializeMouseTracking();
assert.equal(children.length,1);
const marker=children[0];
assert.equal(marker.textContent,'','indicator must be empty');
assert.equal(marker.style.display,'none','initially hidden');
const e=(x,y,button=2,buttons=2)=>({clientX:x,clientY:y,button,buttons,target:{closest:()=>null},preventDefault(){this.prevented=true},stopImmediatePropagation(){this.stopped=true}});
const down=e(610,370);
events.pointerdown[0](down);
assert(m.rightHeld);
assert.equal(marker.style.display,'block');
assert.equal(marker.style.left,'610px');
assert.equal(marker.style.top,'370px');
assert.equal(m.mouseTarget().x,2200);
assert.equal(m.mouseTarget().y,3100);
const move=e(660,370);
events.pointermove[0](move);
assert.equal(marker.style.left,'660px');
assert.equal(m.mouseTarget().x,2300);
// A real living helper only follows the mouse while right is held.
const sent=[];
const c={isConnected:true,clientReady:true,authCompleted:true,probeUrl:main.probeUrl,tabs:[{index:0,playerId:99,player:{cells:[{r:20}],x:50,y:60}}],tabIndex:0,clientId:99,sendCursorPosition(x,y){sent.push([x,y])},sendMessage(){},verificationPending:false};
const bot={index:0,client:c,primary:main,roamTargets:[],nextSplit:0,nextFeed:0,nextSpawn:[],intent:null};
m.bots=[bot]; m.updateSpawn=()=>{};
m.tick();
assert.deepEqual(sent.at(-1),[2300,3100],'bot follows pressed marker');
const up=e(660,370);
events.pointerup[0](up);
assert.equal(m.rightHeld,false);
assert.equal(marker.style.display,'none');
assert.equal(disconnects,1,'default release must disconnect');
// Mouseup after pointerup must not duplicate disconnect.
events.mouseup[0](up);
assert.equal(disconnects,1);
const menu=e(660,370);
events.contextmenu[0](menu);
assert(menu.prevented,'context menu suppressed even after mouseup');
// Optional stop-only preserves sockets and neutralizes cursor.
m.rightReleaseAction='stop';
events.pointerdown[0](e(610,370));
assert(m.rightHeld);
events.pointerup[0](e(610,370));
assert.equal(disconnects,1,'stop only does not disconnect');
assert.deepEqual(sent.at(-1),[50,60],'release sends neutral cursor position');
m.tick();
assert.deepEqual(sent.at(-1),[50,60],'tick does not resume mouse following without right held');
// Right click outside canvas should not intercept.
const outside=e(1200,370);
events.pointerdown[0](outside);
assert(!m.rightHeld && marker.style.display==='none');
// No leaked target if window loses focus.
events.pointerdown[0](e(610,370));
events.blur[0]();
assert(!m.rightHeld && marker.style.display==='none');
console.log('PASS: marker visibility, empty box, world coordinates, held movement, pointerup disconnect, stop-only alternative, focus cleanup, native context menu prevention');
